$ErrorActionPreference = 'Stop'

$path = Join-Path $PSScriptRoot '..\..\apps\api-server\src\services\editingPlanner.service.ts'
$path = [System.IO.Path]::GetFullPath($path)
$content = Get-Content -LiteralPath $path -Raw

if ($content.Contains('freeos-creative-planner-v5-semantic')) {
  Write-Host '[FREEOS] Editing Planner v5 semantic is already installed.' -ForegroundColor Yellow
  exit 0
}

if (-not $content.Contains('freeos-creative-planner-v4-switchpoints')) {
  throw 'Planner must be upgraded to v4 switchpoints before applying v5 semantic.'
}

# Add a deterministic dominant-string helper for window-level semantic aggregation.
$meanMarker = @'
function mean(values: number[]): number | null {
  const finite = values.filter(Number.isFinite);
  return finite.length ? finite.reduce((a, b) => a + b, 0) / finite.length : null;
}
'@
if (-not $content.Contains('function dominantString(')) {
  if (-not $content.Contains($meanMarker)) { throw 'Could not find mean helper.' }
  $dominant = @'

function dominantString(values: unknown[]): string | null {
  const strings = values.filter((value): value is string => typeof value === "string" && value.length > 0);
  if (!strings.length) return null;
  const counts = new Map<string, number>();
  for (const value of strings) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
}
'@
  $content = $content.Replace($meanMarker, $meanMarker + $dominant)
}

# Add semantic evidence to each compacted video window.
$windowNeedle = 'overexposedFraction: mean(frames.map((f) => number(f.overexposedFraction, NaN))),'
if (-not $content.Contains($windowNeedle)) { throw 'Could not find compactVideo window fields.' }
if (-not $content.Contains('shotScale: dominantString(frames.map((f) => f.shotScale))')) {
  $semanticWindow = @'
      personPresence: frames.filter((f) => number(f.personCount, 0) > 0).length / frames.length,
      personCountMean: mean(frames.map((f) => number(f.personCount, NaN))),
      subjectCountMean: mean(frames.map((f) => number(f.subjectCountEstimate, NaN))),
      primaryPersonArea: mean(frames.map((f) => {
        const person = f.largestPerson;
        return person && typeof person === "object" && !Array.isArray(person) ? number((person as JsonObject).areaRatio, NaN) : NaN;
      })),
      globalMotion: mean(frames.map((f) => number(f.globalMotion, NaN))),
      localMotion: mean(frames.map((f) => number(f.localMotion, NaN))),
      shotScale: dominantString(frames.map((f) => f.shotScale)),
      shotScaleConfidence: mean(frames.map((f) => number(f.shotScaleConfidence, NaN))),
      framingRole: dominantString(frames.map((f) => f.framingRole)),
      framingRoleConfidence: mean(frames.map((f) => number(f.framingRoleConfidence, NaN))),
      motionRole: dominantString(frames.map((f) => f.motionRole)),
      motionRoleConfidence: mean(frames.map((f) => number(f.motionRoleConfidence, NaN))),
'@
  $content = $content.Replace($windowNeedle, $windowNeedle + "`r`n" + $semanticWindow.TrimEnd())
}

# Ensure clip summaries expose the analyzer's semantic summary and limitations to the director pass.
$summaryNeedle = 'qualityFlags: video.qualityFlags,'
if (-not $content.Contains($summaryNeedle)) { throw 'Could not find clip summaries.' }
if (-not $content.Contains('semanticNotes: video.semanticNotes,')) {
  $content = $content.Replace($summaryNeedle, $summaryNeedle + "`r`n    semanticNotes: video.semanticNotes,")
}

# Add semantic candidate fields to timeline-first evidence generated by v4.
$candidateNeedle = 'overexposedFraction: w.overexposedFraction,'
if (-not $content.Contains($candidateNeedle)) { throw 'Could not find v4 candidate evidence.' }
if (-not $content.Contains('shotScale: w.shotScale,')) {
  $candidateSemantic = @'
        personPresence: w.personPresence,
        personCountMean: w.personCountMean,
        subjectCountMean: w.subjectCountMean,
        primaryPersonArea: w.primaryPersonArea,
        globalMotion: w.globalMotion,
        localMotion: w.localMotion,
        shotScale: w.shotScale,
        shotScaleConfidence: w.shotScaleConfidence,
        framingRole: w.framingRole,
        framingRoleConfidence: w.framingRoleConfidence,
        motionRole: w.motionRole,
        motionRoleConfidence: w.motionRoleConfidence,
'@
  $content = $content.Replace($candidateNeedle, $candidateNeedle + "`r`n" + $candidateSemantic.TrimEnd())
}

# Make the model explicitly distinguish measured semantics from unsupported narrative invention.
$briefOld = 'Do not output cuts yet. Do not invent footage, lyrics, or musical structure. The academy is judgment guidance, not a preset.'
$briefNew = 'Do not output cuts yet. Do not invent footage, lyrics, performer identity, audience interaction, or musical structure. Treat shotScale, framingRole, motionRole, person evidence, and their confidence values as measured local visual inferences only. If semantic evidence is unknown or low-confidence, say so rather than filling the gap. The academy is judgment guidance, not a preset.'
if ($content.Contains($briefOld)) { $content = $content.Replace($briefOld, $briefNew) }

$sectionOld = 'Do not invent visual content, lyrics, sync, or musical events. The output schema is enforced externally, so output only the edit plan data and never repeat the evidence.'
$sectionNew = 'Do not invent visual content, performer identity, lyrics, sync, audience behavior, or musical events. Use semantic fields only when their confidence supports the inference. Technical metrics are evidence, not a shot-ranking formula. The output schema is enforced externally, so output only the edit plan data and never repeat the evidence.'
if ($content.Contains($sectionOld)) { $content = $content.Replace($sectionOld, $sectionNew) }

# Normalize meaningless same-clip switchpoints after all sections are combined.
$overlapMarker = '  for (let i = 1; i < decisions.length; i++) {'
if (-not $content.Contains($overlapMarker)) { throw 'Could not find combined decision validation.' }
if (-not $content.Contains('const normalizedDecisions: EditingDecision[] = [];')) {
  $normalize = @'
  const normalizedDecisions: EditingDecision[] = [];
  for (const decision of decisions) {
    const previous = normalizedDecisions.at(-1);
    if (previous && previous.clipId === decision.clipId && previous.action === decision.action && Math.abs(previous.end - decision.start) <= 0.02) {
      previous.end = decision.end;
      previous.confidence = Math.min(previous.confidence, decision.confidence);
      if (!previous.rationale && decision.rationale) previous.rationale = decision.rationale;
      continue;
    }
    normalizedDecisions.push({ ...decision });
  }

'@
  $content = $content.Replace($overlapMarker, $normalize + $overlapMarker.Replace('decisions.length','normalizedDecisions.length').Replace('decisions[i]','normalizedDecisions[i]').Replace('decisions[i - 1]','normalizedDecisions[i - 1]'))
}

# Remove internal planner instructions from user-facing creative cautions.
$cautionOld = '    ...sectionCautions,'
$cautionNew = '    ...sectionCautions.filter((caution) => !/^Section must begin with a switch|^Previous section ends at/i.test(caution)),'
if ($content.Contains($cautionOld)) { $content = $content.Replace($cautionOld, $cautionNew) }

# Return normalized decisions and bump planner identity.
$content = $content.Replace('    decisions,', '    decisions: normalizedDecisions,')
$content = $content.Replace('version: "freeos-creative-planner-v4-switchpoints"', 'version: "freeos-creative-planner-v5-semantic"')
$content = $content.Replace('plannerMode: "academy-guided-staged-switchpoints"', 'plannerMode: "academy-guided-staged-semantic-switchpoints"')

$required = @(
  'function dominantString(',
  'shotScale: dominantString(frames.map((f) => f.shotScale))',
  'shotScale: w.shotScale,',
  'const normalizedDecisions: EditingDecision[] = [];',
  'decisions: normalizedDecisions,',
  'freeos-creative-planner-v5-semantic'
)
foreach ($needle in $required) {
  if (-not $content.Contains($needle)) { throw "Semantic upgrade incomplete; missing: $needle" }
}

Set-Content -LiteralPath $path -Value $content -Encoding UTF8
Write-Host '[FREEOS] Editing Planner upgraded to v5 semantic switchpoints.' -ForegroundColor Green
